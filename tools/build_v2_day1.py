def mem(b, key, gate, outs, end):
    """把記憶格插在「她高興完」跟「接回主線」中間。

    直接把 store 掛在 hit 上是沒用的：hole() 已經替 hit 接了一條無條件的線
    往 after-hit，Larch 只認第一條無條件的線，後加的永遠輪不到。
    """
    b.unlink(f"{key}-after-hit", f"{key}-end")
    b.link(f"{key}-after-hit", gate)
    for o in outs:
        b.link(o, end)


