# 保管清單一件一件講。沒有的那幾件跳過，不會出現空白卡。
tell_in = None
gates = []
x = b.col()
for i in range(4):
    g = b.setvar(f"d7-tg{i+1}", [], text="", title=f"保管第 {i+1} 件", x=x, y=i * 620)
    gates.append(g)
    if tell_in is None: tell_in = g
