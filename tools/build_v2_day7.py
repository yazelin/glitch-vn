after_tell = b.setvar("d7-told-done", [], text="", title="講完了", x=x + 1700, y=1900)
for i in range(4):
    y = i * 620
    nxt = gates[i + 1] if i + 1 < 4 else after_tell
    b.link(gates[i], nxt, "right",
           cond={"variable": f"kept{i+1}", "op": "eq", "value": ""})
    c = b.choice(f"d7-tq{i+1}", "這一件要講出來嗎？",
                 [f"講：「{{{{kept{i+1}}}}}」", "這一件先不講"], x=x + 300, y=y)
    b.link(gates[i], c)
    said = b.setvar(f"d7-said{i+1}",
                    [{"variable": "pending", "kind": "set", "valueFrom": f"kept{i+1}"},
                     {"variable": "toldCount", "kind": "add", "value": 1}],
                    text="{{name}} 說……\n「{{kept" + str(i + 1) + "}}」\n\n"
                         "（她停住了。）\n……\n欸。\n對耶。\n我有這件事。",
                    title="講出來", x=x + 700, y=y - 150)
    skip = b.say(f"d7-skip{i+1}", "你沒有講。", who="旁白", x=x + 700, y=y + 150)
    b.link(c, said, "choice-0"); b.link(c, skip, "choice-1")
    g2, o2 = b.store(f"d7-m{i+1}", "「等一下。」有一格自己掉出去了，她沒有發現。",
                     x=x + 1050, y=y - 400)
    b.link(said, g2)
    for o in o2: b.link(o, nxt)
    b.link(skip, nxt)
b.prev = after_tell

