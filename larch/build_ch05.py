#!/usr/bin/env python3
"""第五章・第一次問。本文在 novel/ch05.md。"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from novelkit import Chapter, ensure_characters, prop, G, HOLE

cids = ensure_characters()
c = Chapter("ch05", "第五章・第一次問",
            "諾亞每次都重新回答一次，因為她每次都是第一次問。", cids)
N = "諾亞"

# ── 一 ──────────────────────────────────────────────
c.scene("公寓門口", "凌晨一點。她又把自己鎖在門外了。", "bg-apartment-hall",
        start=True, transition="fadeBlack", ms=600)
c.stage(G)
c.narrate("她又把自己鎖在門外了。")
c.narrate("理論上這件事不應該發生。門鎖是電子的，她的權限寫在系統裡，她根本不需要鑰匙。",
          "可是這棟樓的門鎖是二十年前裝的，二十年前的東西有一個很麻煩的特性："
          "它有時候會需要你拿一張實體的卡片，貼在一個實體的位置上。")
c.narrate("那張卡片現在在屋子裡面。")
c.narrate("她在走廊上站了大概四十秒，把所有可行方案排了一遍，"
          "包括打給房東（凌晨一點）、打給黑洞先生（他在裡面睡覺，而且他沒有手機）、以及等到早上。")
c.narrate("然後樓梯間傳來腳步聲。")
c.stage((G, "left"), (N, "right"))
c.say(N, "又鎖起來了喔。", emotion="笑")
c.say(G, "你怎麼知道我鎖起來了。")
c.say(N, "因為妳站在門口。",
      "站在門口的人只有兩種，一種是忘記帶東西，一種是不想進去。妳看起來不像第二種。")
c.narrate("諾亞從樓下上來，一手拎著工具袋。這種時間還在外面跑，大概是誰家的東西壞了。",
          "他穿著那件磨到發亮的工作背心，"
          "額頭上推著一副雙目放大鏡，其中一顆鏡片裡面鑲著一根真空管，會發出很淡的橘光。",
          "他走路的時候那個橘光會晃。")
# 這裡是撬鎖，不是修東西。「在修東西」那張手上拿的是烙鐵。
c.narrate("他從工具袋裡拿出一根很細的金屬條，蹲下來，在門把下面弄了大概十秒。",
          face=(N, "撬鎖"))
c.narrate("門開了。")
c.say(G, "……這樣好像不太合法。")
c.say(N, "這是我裝的門。", "二十二年前。")
c.narrate("他站起來，膝蓋發出一個很大的聲音。")

# ── 二 ──────────────────────────────────────────────
c.stage()
c.scene("諾亞的店", "頂樓加蓋，裡面堆滿收音機。", "bg-noah-shop", transition="wipeLeft")
c.narrate("隔天下午她去了他的店。")
c.narrate("那間店在頂樓加蓋，門口掛著一塊木牌，木牌上的字已經看不太清楚了。",
          "沒有人會把店開在頂加。那塊木牌本來掛在樓下的騎樓，店收掉以後東西全部搬上來，"
          "招牌也一起搬。現在那裡是倉庫、工作室，也是他睡覺的地方。",
          "裡面堆滿收音機，木頭外殼的、塑膠外殼的、有些沒有外殼，"
          "露出裡面一排一排的零件，像剖開的東西。")
c.stage((N, "left"), (G, "right"))
c.say(G, "請問這裡有賣音源轉接線嗎。")
c.narrate("諾亞從桌子後面抬起頭。")
c.talk((N, "有啊。妳要哪一種。"),
       (G, "就是……一頭細的，一頭粗的那種。"),
       (N, "三點五轉六點三。"),
       (G, "對，那個。"))
c.narrate("他從櫃檯下面拿出一條線，放在檯面上。那條線已經拆好包裝了，捲得很整齊，"
          "用一條橡皮筋束著。")
c.talk((G, "多少錢。"), (N, "一百二。"), (G, "好。"))
c.narrate("她付了錢，把線收進包包。",
          "包包裡已經有兩條一模一樣的線，捲得一樣整齊，束著一樣的橡皮筋。",
          "她沒有看見，因為她沒有翻。那個包包她從來不清。")

# ── 三 ──────────────────────────────────────────────
c.narrate("她沒有馬上走。她在店裡待了大概一個小時，"
          "因為諾亞在修一台很大的收音機，而那件事看起來很有趣。")

# 支線
c.branch("店裡有三樣東西在等人問。",
         ("門口那塊木牌",
          ("木牌上的字被曬到只剩下筆畫的影子，讀不出來。",
           "他每天開門還是把它掛出去。")),
         ("架上最高那一排",
          ("最高那一排全部都修好了，插上電就會響。",
           "上面積的灰比別排厚。修好的東西沒有人來拿。")),
         ("桌角那本簿子",
          ("桌角有一本簿子，記著每一台機器的日期與症狀，字很大很方正。",
           "最新的一行是三年前。之後他就不記了，可是簿子還攤在那裡。")))
c.talk((G, "這台是什麼。"),
       (N, "一九六四年的。真空管的。這種東西現在沒有人修了，因為零件停產四十年了。"),
       (G, "那你怎麼修。"), (N, "拆別台的。"), (G, "那別台不就壞掉了。"),
       (N, "本來就壞掉了。我這裡沒有一台是好的。我是把很多台壞的，湊成一台會響的。"),
       emotion="在修東西", who=N)
c.narrate("她想了一下。")
c.say(G, "那那台算是哪一台。")
c.narrate("諾亞抬起頭，看了她一眼。",
          "那是一種老人在聽到一個他沒想過的問題時會有的表情，眉毛先動，然後才是眼睛。")
c.say(N, "妳這個問題很難。", emotion="想事情")
c.narrate("然後他低頭繼續焊。過了大概五分鐘，他又開口。")
c.talk((N, "妳是做什麼的。"), (G, "我做直播。"), (N, "什麼播。"),
       (G, "就是……我在網路上講話，然後有人看。"), (N, "有多少人。"),
       (G, "兩年前是七個。現在大概四千。"))
c.narrate("諾亞點點頭，那個點頭的樣子完全不像知道四千是多少。")
c.say(N, "那不錯啊。", "我這裡修好的收音機，一台都沒有人聽。", emotion="笑")

# ── 四 ──────────────────────────────────────────────
c.narrate("離開之前她看到桌子底下有一個鞋盒。",
          "鞋盒側面用麥克筆寫著四個字：樓下小姑娘。")
c.talk((G, "那是什麼。"), (N, "妳留在這裡的東西。"))
c.narrate("傘是雨停之後忘在門邊的。手套只有一隻，另一隻不知道去哪了。")
c.narrate("他把盒子拉出來，掀開。裡面有兩把傘、一隻手套、一支螺絲起子、"
          "一個看起來完全不知道用途的小零件，還有一張紙。")
c.talk((G, "螺絲起子是我借你的。"), (N, "是我借妳的。"), (G, "……喔。"),
       (N, "已經三年了。不過沒關係，我有很多支。"), emotion="和藹", who=N)
c.narrate("她拿起那張紙。那是一張收據，很舊，邊角捲起來。上面印的日期是兩年多以前。",
          "品項那一欄寫著：天線用同軸線 3M。",
          props=(prop("prop-receipt"),))
c.narrate("她看著那張收據看了很久。")
c.talk((G, "這個是我買的？"), (N, "是啊。"), (G, "我買天線的線幹嘛。"),
       (N, "妳說妳要接一個東西。妳那天很緊張。"), (G, "我緊張什麼。"),
       (N, "妳沒有講。"))
c.narrate("他把盒子推回桌子底下。")
c.say(N, "我也沒有問。")

# ── 五 ──────────────────────────────────────────────
c.stage()
c.scene("樓梯口", "晚上七點多。兩個人在樓梯口交會。", "bg-stairs", transition="fade")
# 她人在場，這一段是她看著那兩個人。原本台上只有那兩個，旁白卻寫「格莉奇後來想」。
c.stage((N, "farLeft"), (HOLE, "left"), (G, "right"))
c.narrate("那時候是晚上七點多，他剛下班回來，西裝下襬擦過地板，短靴一隻一隻踩在磁磚上。",
          "諾亞剛好也從頂樓下來，要去倒垃圾。")
c.narrate("兩個人在樓梯口交會。")
c.narrate("諾亞點了一下頭。")
c.narrate("黑洞先生也點了一下頭。")
c.stage((G, "right"))
c.narrate("然後兩個人就各走各的了。諾亞沒有看那件外套一眼。",
          "格莉奇後來想，這兩個人認識多久了，她從來沒有問過。")

# ── 六 ──────────────────────────────────────────────
c.scene("諾亞的店", "她走進店裡的第三次是那個禮拜的第三次。", "bg-noah-shop",
        transition="wipeLeft")
c.stage((N, "left"), (G, "right"))
c.talk((G, "請問這裡有賣音源轉接線嗎。"),
       (N, "有啊。妳要哪一種。"),
       (G, "就是一頭細的，一頭粗的那種。"),
       (N, "三點五轉六點三。"),
       (G, "對，那個。"))
c.narrate("他從櫃檯下面拿出一條線。已經拆好包裝，捲得很整齊，橡皮筋束著。")
c.narrate("她付了錢，把線收進包包。")
# 讀者看得到、她看不到。這比再找一個藉口解釋「線都跑到哪裡去了」誠實。
c.narrate("三條線並排躺在包包底部，橡皮筋的顏色一樣，捲的圈數一樣。",
          "她看不到，因為她沒有低頭。")
c.narrate("然後她站在那裡沒有走。")
c.talk((G, "諾亞先生。"), (N, "嗯。"), (G, "我這個禮拜是不是來過了。"))
c.narrate("諾亞把焊槍放到架子上。")
c.say(N, "來過三次。", emotion="想事情")
c.narrate("她沒有說話。")
c.say(N, "連這次。")
c.talk((G, "……那你知道喔。"), (N, "知道啊。"), (G, "那你為什麼每次都重新回答一次。"))
c.narrate("諾亞想了一下。他想得很認真，"
          "那個表情跟他被問「那台算是哪一台」的時候一模一樣，"
          "好像這個問題確實很難，需要花點時間。")
c.say(N, "因為妳每次都是第一次問啊。", emotion="笑")
# 他不能拒收——拒收就是拆穿，她會問為什麼。所以他收下，然後放進她的盒子。
c.narrate("他把那一百二十塊放進桌子底下那個鞋盒。盒子側面寫著樓下小姑娘。")
c.narrate("然後他把手伸到櫃檯下面，拿出下一條線，拆好包裝，捲整齊，"
          "用橡皮筋束起來，放在原來的位置上。")

c.jump("ch06", "ch06-001", "（接第六章・考完就刪）")
c.push("第五章")
