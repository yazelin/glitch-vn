#!/usr/bin/env python3
"""第一章・第一千零四版。

本文在 novel/ch01.md。這一支是**改編**，不是轉檔：
小說裡誰在講話是靠上下文讀出來的，視覺小說要指名道姓，而且要決定誰站在哪、
哪幾句併成一張卡。那是判斷，不是解析。
"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from novelkit import Chapter, ensure_characters, G, HOLE

cids = ensure_characters()
c = Chapter("ch01", "第一章・第一千零四版",
            "兩週年直播散場之後。她照例抄了守則本的第一頁。", cids)

# ── 一 ──────────────────────────────────────────────
c.scene("第一章・第一千零四版", "凌晨兩點十四分。", "bg-studio-2am", start=True)
c.narrate("凌晨兩點十四分，兩週年紀念直播的同時觀看人數是一。")
c.narrate("最高的時候有四千三百人。彩帶動畫放了六次，抖內的提示音疊在一起像一台壞掉的鬧鐘，"
          "她笑到聲音沙啞。",
          "十二點一過人就開始散，像退潮。兩點以後就剩一個。")
c.stage(G)
c.narrate("格莉奇沒有關台。她把音軌一條一條收掉，關掉特效，把待機畫面的亮度調暗兩格，"
          "順手改了明天的排程。",
          "她算過，禮拜三下午開台的到訪率比晚上高百分之九。沒有人相信她真的算得出這種東西。")
c.narrate("留言區跳出一行字。")
c.chat("貓草：終於安靜了")
c.say(G, "你講得好像剛剛是我把他們找來的。")
c.chat("貓草：本來就是", "貓草：你今天發了三則預告")
c.say(G, "兩則。第三則是斑比自己轉的。")
c.narrate("貓草停了幾秒。她一邊等一邊把冷掉的披薩推遠一點。",
          "那是她昨天叫的。她不吃東西，她只是喜歡桌上有食物的樣子。")
c.chat("貓草：反正太吵了", "貓草：還是以前好", "貓草：兩年前只有我們七個人的時候")
c.say(G, "少來。", "那時候你連抖內按鈕在哪都找不到。")
c.chat("貓草：……", "貓草：那是介面設計問題")
c.say(G, "那是你老花。")
c.chat("貓草：我二十三歲")
c.say(G, "你的帳號等級八十級。八十級的人不會說『反正太吵了』。",
      "八十級的人會說『我全都要』。")
c.chat("貓草：…………")
c.narrate("她笑了。這種笑她不太在直播上用，嘴角先動，天線慢半拍才跟上。")
c.chat("貓草：欸", "貓草：那個新來的", "貓草：很吵")
c.say(G, "哪一個？")
c.chat("貓草：一直問你為什麼不接工商的那個")
c.say(G, "他問得很有禮貌啊。")
c.chat("貓草：他昨天也在", "貓草：前天也在")
c.say(G, "所以？")
c.narrate("貓草沒有回。過了大概二十秒。")
c.chat("貓草：沒有", "貓草：晚安", "貓草已離線。")
c.narrate("同時觀看人數變成零。",
          "她看著那個零，說了一句晚安，雖然已經沒有人聽得到了。")

# ── 二 ──────────────────────────────────────────────
c.stage()
c.scene("客廳", "電視亮著，播的是沒有訊號的雜訊。", "bg-living-night")
c.narrate("客廳沒開燈。電視亮著，播的是沒有訊號的雜訊，一整片黑白的雪。",
          "黑洞先生坐在沙發上看那個。")
c.stage((HOLE, "right"))
c.narrate("他是一套西裝。準確地說，西裝底下沒有腿，有一叢觸手，每一根都套著一隻短靴。",
          "今天是十一隻。門邊那疊沒人穿的短靴又高了一點。")
c.stage((G, "left"), (HOLE, "right"))
c.talk((G, "你在看什麼？"), (HOLE, "雪。"), (G, "那是沒訊號。"), (HOLE, "嗯。"))
c.narrate("她從冰箱拿出一塊麵包。昨天的，用保鮮膜包著，邊角折得很仔細。",
          "她不記得是誰包的。包裝手法比她現在好很多，所以她推測是自己包的，那天狀態應該不錯。")
c.say(G, "給你。")
c.narrate("黑洞先生接過去，拉開西裝外套的內側。裡面是黑的。",
          "那種你看進去之後會開始等眼睛適應、然後發現眼睛不會適應的黑。",
          "麵包進去，沒有聲音。")
c.say(HOLE, "今天累嗎。")
c.narrate("他問句從來不用問號的語氣。")
c.talk((G, "四千三百人。"), (HOLE, "嗯。"), (G, "你知道那是多少嗎？"))
c.narrate("黑洞先生想了一下。")
c.talk((HOLE, "比七多。"), (G, "……對。比七多很多。"))
c.narrate("她在他旁邊坐下。電視繼續下雪。")
c.talk((G, "鐵塔今天又傳訊息。他要我開限時周邊。他說『你的記憶梗現在很有話題性』。"),
       (HOLE, "妳怎麼回。"),
       (G, "我說我考慮一下，然後把訊息標成未讀。"),
       (HOLE, "妳很擅長這個。"),
       (G, "我很擅長很多事。"))
c.narrate("這句是真的。她的語言模型跑得比同期任何一台都快，"
          "她可以一邊講話一邊算完整個月的營運成本，她記得住自己講過的每一個笑話。",
          "只要那個笑話是今天講的。")
c.narrate("黑洞先生沒有再說話。他很少說話。",
          "她已經習慣了，而且她私下覺得這樣很好。一個不會追問的室友，對她這種人來說是奢侈品。")

# ── 三 ──────────────────────────────────────────────
c.stage()
c.scene("茶几", "十一點半的時候她會做一件事。", "bg-table-lamp")
c.narrate("十一點半的時候她會做一件事。現在兩點四十，晚了三個多小時，"
          "不過這不重要，因為她做這件事的時候從來不看時鐘。")
c.narrate("守則本是一本皮面的筆記本，厚到已經不太像筆記本。",
          "她把它攤在茶几上，翻到空白的那一頁，然後翻回前一頁。")
c.stage((G, "left"))
c.narrate("她開始抄。")
c.narrate("抄的時候她的手很穩。她一邊抄一邊在腦子裡把今天的抖內金額減掉平台抽成再減掉稅，"
          "算出一個她待會兒不會記得的數字。",
          "她抄得很快，因為抄過很多次。她抄得很準，因為她本來就不會抄錯字。")
c.narrate("第一頁永遠先抄。這是規矩。")
c.stage()
c.narrate("筆尖碰到紙面的那一秒，有一件事發生了。",
          "那件事每天都發生，而她每天都沒有注意到，因為注意到它需要記得昨天也發生過。")
c.narrate("她的眼神空了大概半秒。")
c.narrate("那不是當機。她的處理器沒有停，她的手也沒有停。",
          "空掉的只有一個很小的地方：那個應該要回答「我為什麼要抄這一頁」的地方。",
          "她伸手進去，裡面什麼都沒有，像口袋破了一個洞。")
c.narrate("然後她的邏輯系統給了她一個答案。過去七百多天裡，它給過七百多次同一個答案：")
c.narrate("這很重要。抄。")
c.narrate("她就抄了。")

# ── 四 ──────────────────────────────────────────────
c.narrate("抄完的那一頁長這樣。", "最上面一行是日期。底下是七個項目。")
c.narrate("@CatGrass_80", "@Tower_Manager", "@Null_0x99",
          "@Bambi_Draft3", "@Radio_Noah", "@考完就刪")
c.narrate("第七行是一句話。字跡跟前面六行一樣，是她的字。")
c.narrate("還有一個。不要問他是誰。")
c.stage((G, "left"))
c.narrate("在闔上本子之前，她做了一件她每天都做的事。", "她數了一次。")
c.say(G, "一、二、三、四、五、六。")
c.narrate("六個 ID，加上第七行那句話。")
c.narrate("她盯著那句話看了三秒。",
          "她是一個很聰明的 AI，她當然知道這裡有問題。七個人應該有七個名字，這裡只有六個。",
          "她甚至可以在三秒之內列出四種合理的解釋，其中兩種連她自己都覺得很有說服力。")
c.narrate("可是那句話已經先回答她了。")
c.narrate("不要問他是誰。")
c.narrate("那是她的字。她認得自己的字。")
c.stage()
c.narrate("所以她闔上本子，關掉客廳最後一盞燈，回房間去了。",
          "就像昨天那樣，也像前天那樣，"
          "也像那個她再也數不清、而這本本子替她數到第一千零四次的那樣。")

c.end("第一章結束")

c.push("第一章")
