# 台詞裡的（括號）是舞台指示：（沒有抬頭）（想了一下）（笑）。
# **畫面上要留著，唸出來就錯了。** 2026-09-14 使用者實聽抓到——板上 87 句
# （去重後）含括號，每一句都把動作唸了出來。替身表甚至還把「（指螢幕）」
# 改成「（指顯示器）」：我們仔細修了一個根本不該被唸的詞的讀音。
PAREN = re.compile(r"[（(][^）)]{0,30}[）)]")
# Larch 的執行期變數（`{{page1_text}}` 這種）**不可以唸**。那些字是板子在跑的時候
# 才填進去的，內容是玩家自己寫的，預錄的音檔不可能對。2026-09-14 使用者實聽抓到：
# 三張卡把 `{{page1_lead}}`、`{{page1_text}}`、`{{list_text}}` 照字面唸了出來。
# 拿掉之後整句空掉的（inv-451、inv-452 那兩張整張只有一個變數），
# 會被「沒有可唸的字」那一關擋下來，自動不配音——那是對的，動態內容本來就配不了。
VAR = re.compile(r"\{\{[^}]{0,40}\}\}")


# ── 「行」唸 háng 還是 xíng ──────────────────────────────────────────────
# 這本書裡的「行」幾乎都是本子上的一行（háng），模型會唸成 xíng。
# **本人 2026-09-15 拍板：補一個「字」撐開這個詞，不要用同音的「航」。**
# 同音替身在這個字上驗不了——ASR 分不出 xíng 與 háng（兩邊都聽寫成「行」），
# 工具是瞎的，只能靠耳朵。他聽過三個版本之後選了補字這一版。
#
# 四個例外是照全書 90 處實際上下文量出來的，不是猜的：
#   後面已經有「字」    「跳出一行字」→ 不可以變成「一行字字」
#   前面是「做」        「做這行的都看過」是行業，不是一行字
#   疊字               「一行一行抄」→「一行字一行字抄」很怪
#   後面接名詞          「幾百行歌詞」→「幾百行字歌詞」不通
# 真的是 xíng 的（行程表、銀行、瓦斯行、材料行、行政中心、人行道、
# 行銷預算、可行方案、不行、平行、行事曆）一個都不在數字後面，所以不會中。
HANG = re.compile(r"(?<!做)(?<!行)([一二兩三四五六七]|幾百|那)行(?!字)(?!一行)(?!歌詞)")


def to_speech(text):
    """把要顯示的文字換成要唸的文字。"""
    text = VAR.sub("", text)
    text = PAREN.sub("", text)
    # **劃掉的字要唸，劃掉的記號不要唸。** 卡片上用組合字元 U+0336 畫刪除線
    # （Larch 播放器沒有 markdown 解析器，`~~` 會顯示成兩個波浪號，
    # 2026-09-15 讀播放器 bundle 確認過）。那個字元對合成端沒有意義，
    # 留著會讓 pypinyin 與模型看到不認得的碼位。
    text = text.replace("\u0336", "")
    # 括號拿掉之後留下的空行與行首空白要收乾淨，不然合成端會多一個停頓
    text = re.sub(r"[ \u3000]+", " ", text)
    text = "\n".join(ln.strip() for ln in text.split("\n"))
    text = re.sub(r"\n{2,}", "\n", text).strip()
    for a, b in SUB.items():
        text = text.replace(a, b)
    text = HANG.sub(r"\1行字", text)
    return text


