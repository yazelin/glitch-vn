def key(speaker, text, emotion=None):
    """一句話的穩定代號。

    情緒也算進去——同一句話用不同語氣唸是兩個音檔，不可以共用。
    """
    h = hashlib.sha1(f"{speaker}|{text}|{emotion or ''}".encode("utf-8")).hexdigest()[:16]
    return f"v-{h}"


