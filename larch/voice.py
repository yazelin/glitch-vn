# 所以每一句都掛上，不是只補某個角色——674 句要一致。
ACCENT = "用台灣腔的中文說"


def instruct(speaker, emotion=None):
    """一句台詞要用的表演指示。找不到情緒就退回角色底色。"""
    base = None
    if emotion:
        base = EMO.get((speaker, emotion))
    if base is None:
        base = BASE.get(speaker)
    if base is None:
        return None
    return f"{ACCENT}，{base}"


