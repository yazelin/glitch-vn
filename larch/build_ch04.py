#!/usr/bin/env python3
"""第四章・第四十版。本文在 novel/ch04.md。"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from novelkit import Chapter, ensure_characters, G, HOLE

cids = ensure_characters()
c = Chapter("ch04", "第四章・第四十版",
            "斑比有兩年份的截圖。開台第五天那一頁，第七行是一個 ID。", cids)
B = "斑比"

# ── 一 ──────────────────────────────────────────────
c.scene("斑比的工作室", "桌子上有兩台螢幕、一台繪圖板、七個馬克杯。", "bg-bambi-studio",
        start=True, transition="fadeBlack", ms=600)
c.stage((B, "left"), (G, "right"))
c.narrate("斑比的工作室是一個房間，房間裡有一張桌子，"
          "桌子上有兩台螢幕、一台繪圖板、七個馬克杯。")
c.narrate("七個馬克杯裡面有六個是空的。")

# 支線
c.branch("這張桌子上有三樣東西比人先講話。",
         ("七個馬克杯",
          ("六個是空的，杯底都留著一圈深褐色的環。環的顏色一層疊一層，數得出來不只六次。",
           "有一個杯子的把手用膠帶纏過。")),
         ("牆上的參考圖",
          ("牆上釘滿列印出來的截圖，全部是同一個人的動作：抬手、側頭、天線抖一下。",
           # 原本寫「沒有一張是她的臉」，讀起來會變成斑比自己的臉，而且重點沒講出來。
           "沒有一張拍到臉。臉是斑比自己畫的，她不需要參考；她要的是格莉奇怎麼動。")),
         ("那台休眠的螢幕",
          ("休眠的那台螢幕在間隔很久之後會亮一下，跳出待機畫面。",
           "待機畫面是一張很舊的立繪，線條比現在硬，配色比現在暗。")))
c.say(B, "那個是昨天的。還可以喝。", emotion="累")
c.talk((G, "我不喝東西。"), (B, "喔對。"))
c.narrate("斑比把杯子推遠一點，那個動作跟格莉奇推披薩的動作幾乎一樣，"
          "只是斑比推完之後又把它拉回來了。")
c.narrate("她的十根手指上纏著不同顏色的指套跟膠布，淡紫色、霓虹藍，有幾圈已經翹起來。",
          "她畫圖的時候會用力壓筆，壓到指節發白，所以她纏那些東西。",
          "她跟格莉奇解釋過三次這件事，三次都是格莉奇問的。")

# ── 二 ──────────────────────────────────────────────
c.say(B, "這是第四十版。", emotion="不安")
c.narrate("螢幕上是格莉奇的立繪。新的表情差分，微笑，眼睛稍微瞇起來的那一種。")
c.say(G, "這比第三十九版好嗎。")
c.narrate("格莉奇看著螢幕。")
c.narrate("她不記得第三十九版。她也不記得第三十八版、第三十七版、或者第十二版。",
          "這件事斑比知道，斑比每次都還是會問，"
          "而格莉奇每次都不會說「我不記得」，因為那樣講很煩，而且沒有用。")
c.say(G, "我不知道這比第三十九版好不好。", "可是這一版的嘴角有一邊比較高。")
c.talk((B, "那是故意的。"),
       (G, "我知道那是故意的。我的意思是，這樣看起來像是我剛剛想到一件很好笑的事情，"
           "可是我還沒有講出來。"))
c.narrate("斑比沒有回話。")
c.say(G, "這樣可以嗎。")
c.say(B, "……可以。", emotion="被說中")
c.narrate("她的聲音有一點怪。")
c.say(B, "這是兩年來第一次有人跟我講畫面上有什麼。",
      "其他人都只會說『這版比較好』或者『這版怪怪的』。", emotion="被說中")
c.talk((G, "那是因為他們記得前面三十九版。"), (B, "對。所以他們都在比。"))
c.narrate("她把筆蓋從嘴裡拿出來，又放回去。")
c.say(B, "妳是唯一一個每次都在看的人。", emotion="被說中")

# ── 三 ──────────────────────────────────────────────
c.say(B, "還有一件事。樣品那本要重做。")
c.narrate("斑比切到另一個檔案。那是那本假守則本的第一頁，模擬手寫的示範內容。")
c.say(B, "鐵塔說內頁要重排，字體太像真的，法務那邊有意見。", "所以我要重畫一次。")
c.talk((G, "好。"), (B, "可是我要先問妳一件事。"))
c.narrate("斑比把畫面放大。")
c.say(B, "這裡為什麼是七行。", emotion="專注")
c.narrate("格莉奇看著那七行假字。")
c.say(B, "我畫的時候是照著妳直播畫面上出現過的樣子。",
      "妳寫守則本的時候鏡頭有拍到，我截過圖。第一頁我數過，七行。所以我畫七行。")
c.say(G, "嗯。")
c.say(B, "可是妳的本子第一頁只有六個名字。", emotion="專注")
c.narrate("房間裡的空調在運轉。斑比的其中一台螢幕進入了休眠。")
c.say(G, "妳怎麼知道。", emotion="驚訝")
c.say(B, "因為我截的圖裡面數得出來。六個 ID，加上一行不是 ID 的東西。所以嚴格講是六加一，不是七。",
      "我想問的是那一行要不要照畫，因為如果照畫，那看起來就會很像妳的本子，法務可能會有意見。")

# ── 四 ──────────────────────────────────────────────
c.say(G, "妳的截圖。有多久以前的。")
c.say(B, "我從妳開台就在截了。參考圖啊。畫立繪要看妳自己的動作習慣，不然畫出來會很假。")
c.narrate("她說得很自然，像在講一件很無聊的事。")
c.talk((G, "所以妳有兩年份。"), (B, "大概。有些硬碟壞掉了。"), (G, "最早的那一張。"))
c.narrate("斑比翻了一下資料夾。滑鼠滾輪的聲音很久。")
c.say(B, "這一張。開台第五天。")
c.narrate("畫質很爛。那是兩年前的串流碼率，而且是從一段會動的畫面截下來的，"
          "糊得像有人在紙上呵了一口氣。")
c.narrate("可是可以數。")
c.narrate("一行，兩行，三行，四行，五行，六行。")
c.narrate("第七行。")
c.narrate("第七行是一個字串。它的長度跟前面六行差不多，"
          "開頭有一個小小的、方形的東西，糊掉了，"
          "可是它的形狀比較像一個 @，不太像一個字。")
c.talk((G, "這一行是名字。"), (B, "妳自己的本子上不是嗎。"),
       (G, "不是。我的第七行是一句話。"))
c.narrate("斑比看著螢幕，看了大概五秒。")
c.say(B, "喔。那妳改過。", emotion="不安")

# ── 五 ──────────────────────────────────────────────
c.stage()
c.scene("茶几", "回家之後她沒有先開電視。", "bg-table-lamp")
c.stage((G, "left"))
c.narrate("回家之後她沒有先開電視。")
c.narrate("她把守則本攤在茶几上，翻到最新的那一頁，看了一眼第一頁的內容，然後往前翻。")
c.narrate("第一千零三版。一樣。", "第一千零二版。一樣。")
c.narrate("她開始往回翻。她翻得很快，因為她本來就做得到；"
          "她一頁一頁掃過去，六個 ID 加一行字，六個 ID 加一行字，六個 ID 加一行字。",
          "她一邊翻一邊在心裡估算：如果那個改動發生在某一版，"
          "那一版之前的第一頁就會長得不一樣，而她只要找到那個交界就好。"
          "這是一個很簡單的搜尋問題。")
c.narrate("她一邊翻一邊順手算了一件她從來沒有算過的事。")
c.narrate("這本本子現在是第一千零四版。可是她的頻道只開了兩年，兩年是七百三十天。")
c.narrate("所以這本本子比頻道老。她在開始講話給別人聽之前，"
          "就已經每天晚上在寫東西給明天的自己了。",
          "這件事她也不記得，可是算術不會騙人。")
c.narrate("她翻了大概兩百版。")
c.narrate("然後她的手停了。")
c.narrate("不是因為她找到了。")
c.narrate("是因為書頁沒有了。")
c.narrate("那本本子的前面被撕掉了。撕得很整齊，貼著書脊，留下一排很窄的紙邊，"
          "像一整排斷掉的牙。",
          "她用手指摸過去，可以摸到那些紙邊的厚度。"
          "她算了一下：以每一版的紙厚推估，這裡少掉大概八百頁。")
c.narrate("她把本子翻到最前面。")
c.narrate("現在的第一頁，是第八百多版。")
c.stage((G, "left"), (HOLE, "farRight"))
c.narrate("黑洞先生在她背後的走廊上經過，短靴踩在地板上有很輕的聲音。",
          "他停了一下，然後繼續往房間走。")
c.narrate("格莉奇沒有回頭。")
c.say(G, "你有看過這本本子的前面嗎。")
c.narrate("腳步聲停了。")
c.say(HOLE, "沒有。")
c.stage((G, "left"))
c.narrate("那是他今天說的第一句話，而且是實話。")

c.jump("ch05", "ch05-001", "（接第五章・第一次問）")
c.push("第四章")
