#!/usr/bin/env python3
"""第二章・限時預購。本文在 novel/ch02.md。"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from novelkit import Chapter, ensure_characters, prop, G, HOLE

cids = ensure_characters()
c = Chapter("ch02", "第二章・限時預購",
            "鐵塔要賣一本假的守則本。樣品的第一頁上有七行。", cids)
T = "鐵塔"

# ── 一 ──────────────────────────────────────────────
c.scene("錄音間", "錄第十一次的時候，鐵塔終於說可以了。", "bg-booth",
        start=True, transition="fadeBlack", ms=600)
c.stage(G)
c.narrate("錄第十一次的時候，鐵塔終於說可以了。")
# 鐵塔全程在耳機裡，不在房間裡。所以他不上台，只出聲。
c.say(T, "剛剛那個『新品上市』，尾音再收乾淨一點。", "妳第七次那個最好，但是第七次前面那句吃字。",
      remote=True)
c.say(G, "我知道。所以我第八次修了前面，你嫌後面。第九次兩邊都對，你說沒有感情。")
c.talk((T, "第九次沒有感情。"),
       (G, "那是因為第九次我在想你為什麼要聽十一次。"), remote=T)
c.narrate("耳機裡傳來撕開包裝紙的聲音，很脆，唰啦一下。")
c.narrate("鐵塔一天要吃很多顆喉糖。她算過，平均每四十分鐘一顆，"
          "而且他從來不含到融化，都是嚼掉的。")
c.say(T, "可以了。", "檔案我下午發出去。", remote=True)
c.narrate("錄音間的隔音牆是深灰色的，上面貼滿吸音棉，一格一格排得很整齊。",
          "她坐在裡面的時候常常想，這個房間的設計目的是讓聲音出不去。")
c.talk((G, "鐵塔。"), (T, "嗯。"),
       (G, "你聽了十一次同一句話，會不會覺得那句話開始變得不像話。"),
       (T, "會。第六次開始。"),
       (G, "那你怎麼還聽得下去。"),
       (T, "因為我不是在聽意思。"), remote=T)

# ── 二 ──────────────────────────────────────────────
c.stage()
c.scene("視訊會議", "會議是視訊，但鐵塔還是穿了西裝。", "bg-booth", transition="wipeLeft")
c.stage((G, "left"), (T, "right"))
c.narrate("會議是視訊，但鐵塔還是穿了西裝。他背後是公司的白牆和一株明顯是塑膠的植物。")
c.say(T, "第一批周邊只有兩個 SKU 賣得動。",
      "壓克力立牌，還有那個貼紙包。剩下的抱枕跟毛巾，倉庫還有八百多件。")
c.talk((G, "那就不要再做抱枕。"), (T, "所以我提了新的。"))
c.narrate("他切到下一頁。頁面上只有一張照片和一行字。",
          "照片是一本皮面筆記本。深棕色，邊角磨損，厚到已經不太像筆記本。")
c.narrate("《守則本》限時預購・附手寫感內頁")
c.narrate("她看了三秒。")
c.talk((G, "這是我的本子。"),
       (T, "這是一本本子。妳的那本我們沒有拍。"
           "這是我請斑比照著妳直播畫面裡出現過的樣子重畫的。版權沒有問題，我確認過。"),
       (G, "我不是在講版權。"),
       (T, "那妳在講什麼。"))
c.narrate("她想了一下。這是她那天做的第一件慢事。")
c.say(G, "我不知道。", "所以你先講你的。")
c.narrate("鐵塔點頭。他喜歡這個回答，因為這個回答可以繼續開會。")
c.say(T, "數據上，妳的『記憶』相關內容互動率是其他內容的三點四倍。"
      "剪輯台的十二支熱門片段裡有九支是這個主題。",
      "觀眾對這件事有情感投射，而目前市面上沒有任何一個對應的實體商品。", emotion="公事")
c.talk((G, "所以你要賣一本我每天晚上都在寫的東西。"),
       (T, "我要賣一本觀眾可以自己寫的東西。"),
       (T, "內頁是空白的。附一張書籤，上面印妳的簽名。定價一千二，首批三千本，毛利四成三。"))
c.narrate("塑膠植物在他背後一動也不動。")
c.say(T, "妳如果不喜歡，我就撤掉。",
      "但我要先講清楚：這一季如果沒有新品，公司會把妳的行銷預算移到 0x 那條線。",
      "這句話是我今天早上開完會被交代要跟妳講的。", emotion="公事")
c.narrate("唰啦。又一顆。")
c.narrate("會議快結束的時候，他把螢幕分享關掉。")
c.talk((T, "妳今天聲音有點啞。"), (G, "錄十一次會啞。"), (T, "明天少講一點話。"),
       emotion="難得的溫柔")
c.narrate("然後他就把視訊掛了。他沒有說再見。他從來不說再見。", face=(T, "掛掉"))
c.stage(G)

# ── 三 ──────────────────────────────────────────────
c.stage()
c.scene("樣品", "樣品是隔天寄到的。", "bg-booth", transition="fade")
c.stage(G)
c.narrate("樣品是隔天寄到的。比她想像的好。")

# 支線
c.branch("樣品盒裡一共三樣東西。",
         ("皮面與車線",
          ("皮是真的，邊角先磨過再上油，車線的針距從頭到尾沒有變過。",
           "斑比在這種事情上從來不打折。這一點沒有人會在商品頁上看到。")),
         ("附的那張書籤",
          ("書籤上印著她的簽名。那個簽名是掃描來的，來源是兩年前某一張簽名板。",
           "她自己現在簽起來已經不長那樣了。")),
         ("外盒上的貼紙",
          ("外盒側面貼著一張還沒撕掉的內部標籤：首批三千本。",
           "標籤底下壓著另一張更早的標籤，數字被蓋住了，只露出一個角。")))
c.narrate("皮面的手感很扎實，車線整齊，翻開的時候書脊會發出一種很小的、"
          "像是有人在遠處清喉嚨的聲音。斑比在這種事情上從來不打折。")
c.narrate("第一頁印著手寫感的示範內容，用的是那種模擬鋼筆的字體。",
          "示範內容是隨便寫的，就是那種為了讓客人知道「這裡可以寫字」而存在的假字。")
c.narrate("她翻到第一頁。")
c.stage()
c.scene("樣品・第一頁", "上面有七行。", "page-sample", transition="irisIn", ms=420)
c.narrate("上面有七行。")
c.narrate("七個假名字，排成一列，字體歪歪的，模仿手寫。")
c.narrate("她盯著那七行看。")
c.narrate("她的處理器沒有停。她可以同時告訴你這個字體叫什麼、這種皮的加工方式、"
          "以及這一頁如果印三千本的單頁成本是多少。她全部都算得出來。")
c.narrate("只有一件事她算不出來：她不知道自己為什麼一直在看那一頁。")
c.narrate("她把樣品闔上，又打開，又翻到第一頁。")
c.narrate("七行。")
c.scene("錄音間", "她說給自己聽的。", "bg-booth", transition="fade")
c.stage(G)
c.say(G, "……七。", emotion="發呆")
c.narrate("錄音間裡沒有人。她說給自己聽的。")

# ── 四 ──────────────────────────────────────────────
c.stage()
c.scene("客廳", "那天晚上她把樣品帶回家，放在茶几上。", "bg-living-night", effect="snow")
c.stage((HOLE, "right"))
c.narrate("黑洞先生看了一眼，繼續看電視。今天播的還是雪。")
c.stage((G, "left"), (HOLE, "right"))
c.talk((G, "這是假的。周邊。"), (HOLE, "嗯。"), (G, "你要嗎。"))
c.narrate("黑洞先生轉過頭來。他看那本假的本子看了很久，久到她開始覺得自己問錯了什麼。",
          "然後他伸手把它拿過去，拉開外套內側，放進去。", face=(HOLE, "拉開外套"),
          props=(prop("prop-book-closed", slot="center", scale=.34),))
c.talk((G, "那是假的欸。"), (HOLE, "我知道。"))
c.narrate("她笑了一下。她本來想再說點什麼，"
          "可是那個要說的東西在她伸手去拿的時候已經不在了，就像每天都會發生的那樣。")
c.narrate("於是她問了另一件事。")
c.talk((G, "黑洞先生。"), (HOLE, "嗯。"), (G, "我們認識多久了。"), (HOLE, "兩年。"),
       (G, "那我認識你之前呢。"))
c.narrate("電視繼續下雪。他沒有回答。", face=(HOLE, "不回答"))
c.narrate("她等了大概十秒。")
c.talk((G, "你不知道也沒關係。"), (HOLE, "妳問過了。"), (G, "什麼時候。"), (HOLE, "很多次。"))
c.narrate("她想笑，可是那個笑沒有出來。她低頭看了一眼茶几，上面現在什麼都沒有了。")
c.talk((G, "那我下次應該不會記得我問過。"), (HOLE, "嗯。"),
       (G, "那你每次都要重新回答一次欸。"))
c.narrate("黑洞先生把外套的內側拉好，扣上一顆扣子。")
c.say(HOLE, "還好。")

c.jump("ch03", "ch03-001", "（接第三章・99.98）")
c.push("第二章")
